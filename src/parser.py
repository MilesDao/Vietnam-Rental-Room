def normalize_raw_post(raw: dict, group_url: str, crawl_time: str) -> dict:
    """Turn one raw JS post object into the canonical schema.

    Applies URL/text/count normalization via ``utils``. ``post_id`` prefers a
    value parsed from the permalink, else the id the extractor recovered
    (e.g. from a comet ``pcb`` photo link). Unknown fields stay ``None`` (or
    ``[]`` for media). Never invents values.
    """
    record = {**EMPTY_POST, "image_urls": [], "video_urls": []}
    record["group_url"] = group_url
    record["crawl_time"] = crawl_time

    post_url = utils.normalize_url(raw.get("post_url"))
    record["post_url"] = post_url
    record["post_id"] = (
        utils.extract_post_id(raw.get("post_url"))
        or (utils.extract_post_id(post_url) if post_url else None)
        or (str(raw["post_id"]) if raw.get("post_id") else None)
    )

    record["timestamp_text"] = raw.get("timestamp_text") or None
    ts = raw.get("timestamp_text")
    if ts and _looks_iso(ts):
        record["timestamp"] = ts

    record["text"] = utils.normalize_text(raw.get("text"))

    record["reaction_count"] = utils.parse_count(raw.get("reaction_text"))
    record["comment_count"] = utils.parse_count(raw.get("comment_text"))
    record["share_count"] = utils.parse_count(raw.get("share_text"))

    record["image_urls"] = _dedup_keep_order(raw.get("image_urls") or [])
    record["video_urls"] = _dedup_keep_order(raw.get("video_urls") or [])

    return record


def _looks_iso(value: str) -> bool:
    """Heuristic: does this timestamp text look like an ISO 8601 datetime?"""
    value = value.strip()
    return len(value) >= 10 and value[4:5] == "-" and value[7:8] == "-"


def _dedup_keep_order(items: list[str]) -> list[str]:
    seen: set[str] = set()
    out: list[str] = []
    for item in items:
        if item and item not in seen:
            seen.add(item)
            out.append(item)
    return out
